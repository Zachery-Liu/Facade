import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';

const bundle = await build({ entryPoints: ['src/themes/product/browser-runtime.ts'], bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true, write: false });
const source = bundle.outputFiles[0]?.text;
if (!source) throw new Error('Browser runtime bundle is empty');
await writeFile('src/themes/product/browser-bundle.ts', `// Generated by scripts/bundle-browser.mjs.\nexport const browserBundle = ${JSON.stringify(source)};\n`, 'utf8');
